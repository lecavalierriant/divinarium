function initialiser() {
	document.getElementById("select-initiales").addEventListener(
		"change",
		function() {
			for (imago of document.getElementsByClassName("img-initiale")) {
				source = imago.src.split("/");
				imago.src = source[source.length - 3] + "/" + this.value + "/" + source[source.length - 1];
			}
		}
	);
}

